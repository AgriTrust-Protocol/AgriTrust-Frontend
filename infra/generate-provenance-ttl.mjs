// Generates the Fuseki instance graph from src/lib/snapshot.ts so the seeded
// triples carry byte-identical content commitments to the frontend snapshot.
// Run: node infra/generate-provenance-ttl.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const SNAPSHOT = resolve(here, "../src/lib/snapshot.ts");
const OUT = resolve(here, "fuseki/batch-COF-LOT-2024-0892.ttl");

const source = readFileSync(SNAPSHOT, "utf8");
const nodesBlock = source.slice(source.indexOf("nodes: ["), source.indexOf("edges: ["));
const edgesBlock = source.slice(source.indexOf("edges: ["));

const NS = "https://agritrust.org/id/batch/COF-LOT-2024-0892";
const ASSET_ID =
  "4f2a9c17e5b3d8064af29c1e7d5b03948a6e2c17f0b9d4e83a6c507f1e2b3d49";

function unescapeTtl(value) {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
}

/** Split a block into `{ ... }` object literals, ignoring braces inside strings. */
function splitEntries(block) {
  const entries = [];
  let depth = 0;
  let start = -1;
  let inString = false;

  for (let i = 0; i < block.length; i += 1) {
    const ch = block[i];
    if (inString) {
      if (ch === "\\") i += 1;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') inString = true;
    else if (ch === "{") {
      if (depth === 0) start = i;
      depth += 1;
    } else if (ch === "}") {
      depth -= 1;
      if (depth === 0 && start >= 0) {
        entries.push(block.slice(start, i + 1));
        start = -1;
      }
    }
  }
  return entries;
}

function field(entry, key) {
  const match = entry.match(new RegExp(`\\b${key}:\\s*"([^"]*)"`));
  return match ? match[1] : undefined;
}

function fieldNumber(entry, key) {
  const match = entry.match(new RegExp(`\\b${key}:\\s*([0-9_]+)`));
  return match ? Number(match[1].replace(/_/g, "")) : undefined;
}

function iriField(entry, key) {
  // Built by concatenation: the pattern contains backticks, which would
  // terminate a template literal.
  const pattern = "\\b" + key + ":\\s*`\\$\\{NS\\}([^`]*)`";
  const match = entry.match(new RegExp(pattern));
  return match ? `${NS}${match[1]}` : undefined;
}

const lines = [];
lines.push(`# AgriTrust :Process provenance graph — batch COF-LOT-2024-0892.`);
lines.push(`#`);
lines.push(`# GENERATED by infra/generate-provenance-ttl.mjs — do not edit by hand.`);
lines.push(`# Content commitments are SHA-256 digests of the node/edge IRIs and are`);
lines.push(`# identical to src/lib/snapshot.ts, so the seeded graph folds to the same`);
lines.push(`# Merkle root the farmer anchored on Soroban.`);
lines.push("");
lines.push("@prefix agritrust: <https://agritrust.org/ontology#> .");
lines.push("@prefix rdf:      <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .");
lines.push("@prefix rdfs:     <http://www.w3.org/2000/01/rdf-schema#> .");
lines.push("@prefix xsd:      <http://www.w3.org/2001/XMLSchema#> .");
lines.push("@prefix prov:     <http://www.w3.org/ns/prov#> .");
lines.push("@prefix geo:      <http://www.opengis.net/ont/geosparql#> .");
lines.push("");

// Batch anchor. LINEAGE_QUERY binds the graph root through this resource.
lines.push(`# --- batch anchor ---`);
lines.push(`<${NS}> a agritrust:CommodityBatch ;`);
lines.push(`    agritrust:assetCommitment "${ASSET_ID}" ;`);
lines.push(`    agritrust:commodity "COFFEE" ;`);
lines.push(`    agritrust:rootNode <${NS}/harvest> ;`);
lines.push(`    agritrust:provenanceMerkleRoot "6754964ce63edb44cf21da33bc88832aece614e42e35aa8be9c02b2867bb79a2" .`);
lines.push("");

lines.push(`# --- nodes ---`);
for (const entry of splitEntries(nodesBlock)) {
  const iri = iriField(entry, "id");
  const kind = field(entry, "kind");
  const label = field(entry, "label");
  const hash = field(entry, "hash");
  const timestamp = field(entry, "timestamp");
  const actor = field(entry, "actor");
  const quantity = fieldNumber(entry, "quantityKg");
  const location = field(entry, "location");
  if (iri === undefined || kind === undefined || hash === undefined) continue;

  const statements = [
    `    rdf:type agritrust:${kind}`,
    `    rdfs:label "${unescapeTtl(label ?? "")}"`,
    `    agritrust:contentHash "${hash}"`,
    `    agritrust:recordedAt "${timestamp}"^^xsd:dateTime`,
    `    agritrust:actor "${unescapeTtl(actor ?? "")}"`,
  ];
  if (quantity !== undefined) {
    statements.push(`    agritrust:quantityKilograms "${quantity}"^^xsd:decimal`);
  }
  if (location !== undefined) {
    statements.push(`    agritrust:location "${unescapeTtl(location)}"`);
  }
  // The EUDR compliance service probes this predicate for Article 10 evidence.
  if (iri.endsWith("/harvest")) {
    statements.push(`    agritrust:deforestationFree "true"`);
  }

  lines.push(`<${iri}>`);
  lines.push(`${statements.join(" ;\n")} .`);
  lines.push("");
}

lines.push(`# --- directional statements ---`);
for (const entry of splitEntries(edgesBlock)) {
  const iri = iriField(entry, "id");
  const from = iriField(entry, "source");
  const to = iriField(entry, "target");
  const kind = field(entry, "kind");
  const hash = field(entry, "hash");
  if (iri === undefined || from === undefined || to === undefined) continue;

  lines.push(`<${iri}>`);
  lines.push(
    [
      `    rdf:type agritrust:LineageStatement`,
      `    agritrust:from <${from}>`,
      `    agritrust:to <${to}>`,
      `    agritrust:predicate agritrust:${kind}`,
      `    agritrust:contentHash "${hash}"`,
    ].join(" ;\n") + " .",
  );
  lines.push("");
}

writeFileSync(OUT, lines.join("\n"));
process.stdout.write(`Wrote ${OUT}\n`);
process.stdout.write(`nodes: ${splitEntries(nodesBlock).length}, edges: ${splitEntries(edgesBlock).length}\n`);